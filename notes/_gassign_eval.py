# --- instance selection -------------------------------------------------------
def parse_instances(spec):
    """Return an ordered list of instance names like ['prob_21', ...]."""
    spec = (spec or "SET2").strip()
    up = spec.upper()
    if up == "SET1":
        return [f"prob_{i}" for i in range(1, 21)]
    if up == "SET2":
        return [f"prob_{i}" for i in range(21, 41)]
    if up == "ALL40":
        return [f"prob_{i}" for i in range(1, 41)]
    out = []
    for tok in spec.split(","):
        tok = tok.strip()
        if not tok:
            continue
        if tok.isdigit():
            tok = f"prob_{tok}"
        out.append(tok)
    return out


def load_instance(name):
    """Load a fresh prob_info dict (fresh each call to avoid mutation)."""
    path = os.path.join(_INSTANCE_DIR, f"{name}.json")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def instance_meta(prob):
    blocks = prob.get("blocks", [])
    bays = prob.get("bays", [])
    weights = prob.get("weights", {}) or {}
    return {
        "n_blocks": len(blocks),
        "n_bays": len(bays),
        "w1": weights.get("w1", 1.0),
        "w2": weights.get("w2", 1.0),
        "w3": weights.get("w3", 1.0),
    }


# --- reference data -----------------------------------------------------------
def load_competitor():
    """Return {instance_name: competitor_obj_float} or {} if unavailable."""
    try:
        with open(_COMPETITOR_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        return {}
    comp = data.get("competitor", {}) if isinstance(data, dict) else {}
    out = {}
    for name, rec in comp.items():
        if isinstance(rec, dict) and rec.get("obj") is not None:
            out[name] = rec.get("obj")
    return out


def load_baseline():
    """Return {instance_name: baseline_obj_float} or {} if unavailable.

    LOOSE reference only (box-OFF legacy@120 run, set2=4.24B) -- labelled as
    loose; never used to judge a win."""
    try:
        with open(_BASELINE_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        return {}
    out = {}
    if isinstance(data, dict):
        for name, rec in data.items():
            if isinstance(rec, dict) and rec.get("obj") is not None:
                out[name] = rec.get("obj")
    return out


def load_production():
    """Return {instance_name: prod_obj_float} from the E0 hybrid json, or {}.

    Reads notes/perbay-e0-all40.json (mirrors _perbay_set2.py output): a top
    dict whose "instances" key is a list of records each with "instance",
    "final_obj", "feasible".  We map instance -> final_obj for FEASIBLE records
    only (an infeasible production record is no valid bar).  Degrades to {} if
    the file is absent (E0 still running) -> per-instance prod_obj shows "--"."""
    try:
        with open(_E0_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        return {}
    out = {}
    insts = data.get("instances", []) if isinstance(data, dict) else []
    if not isinstance(insts, list):
        return {}
    for rec in insts:
        if not isinstance(rec, dict):
            continue
        name = rec.get("instance")
        obj = rec.get("final_obj")
        feas = rec.get("feasible")
        # Only a feasible production result is a valid bar to beat.
        if name and obj is not None and feas is not False:
            out[name] = obj
    return out


# --- one gassign solve --------------------------------------------------------
def run_instance(algorithm, check_feasibility, name, timelimit):
    """Run ONE gassign solve in-process.  Returns a result dict.

    Keys: obj, obj1, obj2, obj3, feasible, wall, status, err.
    status in {OK, INFEASIBLE, NONE, CRASH}.  NONE = gassign returned None.
    """
    # Fresh prob_info -- algorithm() may mutate the dict it is given.
    prob = load_instance(name)

    res = {
        "obj": None, "obj1": None, "obj2": None, "obj3": None,
        "feasible": None, "wall": None, "status": "OK", "err": None,
    }
    t0 = time.monotonic()
    try:
        sol = algorithm(prob, float(timelimit))
        res["wall"] = time.monotonic() - t0
        if sol is None:
            res["status"] = "NONE"
            res["feasible"] = False
            res["err"] = "gassign.algorithm returned None"
            return res
        # Re-load a pristine prob_info for the feasibility check (algorithm may
        # have mutated the one it was given).
        prob_check = load_instance(name)
        fc = check_feasibility(prob_check, sol)
        res["feasible"] = bool(fc.get("feasible"))
        res["obj"] = fc.get("objective")
        res["obj1"] = fc.get("obj1")
        res["obj2"] = fc.get("obj2")
        res["obj3"] = fc.get("obj3")
        if not res["feasible"]:
            res["status"] = "INFEASIBLE"
            res["stage"] = fc.get("stage")
            viol = fc.get("violations") or []
            res["violations"] = viol[:5]
    except Exception as e:
        res["wall"] = time.monotonic() - t0
        res["status"] = "CRASH"
        res["feasible"] = False
        res["err"] = f"{type(e).__name__}: {e}"
        res["traceback"] = traceback.format_exc().splitlines()[-6:]

    return res


# --- HTML helpers -------------------------------------------------------------
def _fmt(x, nd=2):
    if x is None:
        return "&mdash;"
    try:
        if isinstance(x, float):
            return f"{x:,.{nd}f}"
        return f"{x:,}"
    except Exception:
        return _htmlmod.escape(str(x))


def _fmt0(x):
    if x is None:
        return "&mdash;"
    try:
        return f"{x:,.0f}"
    except Exception:
        return _htmlmod.escape(str(x))


def _fmt_delta(x):
    """Signed delta with sign; None -> em-dash."""
    if x is None:
        return "&mdash;"
    try:
        sign = "+" if x > 0 else ""
        return f"{sign}{x:,.0f}"
    except Exception:
        return _htmlmod.escape(str(x))


