def build_findings(records, totals, cfg):
    out = []
    t = totals
    n = len(records)

    # wins
    wins = [(r["instance"], r.get("delta")) for r in records
            if r.get("verdict") == "gassign_win" and r.get("delta") is not None]
    wins.sort(key=lambda x: x[1])  # most negative (biggest win) first
    if wins:
        top = ", ".join(f"{nm} ({d:,.0f})" for nm, d in wins[:5])
        out.append(
            "gassign BEATS production on {w}/{n} instance(s) (feasible & lower obj). "
            "Biggest wins: {top}.".format(w=len(wins), n=n, top=top))
    else:
        out.append(
            "gassign beats production on NO instance (no feasible gassign result "
            "was strictly below the hybrid bar).")

    # delta total
    td = t.get("total_delta")
    if td is not None:
        sign = "BELOW (better than)" if td < 0 else "ABOVE (worse than)"
        out.append(
            "Total &Delta; over instances feasible in BOTH = {td:,.0f} -- gassign is "
            "{sign} the production hybrid in aggregate.".format(td=td, sign=sign))
    else:
        out.append(
            "No instance was feasible in both gassign and production (or the E0 "
            "production json is absent) -- total &Delta; not computable.")

    # feasibility / -1
    infeas = [r["instance"] for r in records if r.get("feasible") is False]
    if infeas:
        out.append(
            "CRITICAL: gassign INFEASIBLE / None / crash on: {il} -- each is a -1 "
            "(~ -R/2 in scoring). gassign is standalone (no best-of guard) so these "
            "would be real -1s if shipped alone.".format(il=", ".join(infeas)))
    else:
        out.append("gassign was feasible on every selected instance (never -1).")

    # max wall vs TL
    if t.get("max_wall") is not None:
        over = t["max_wall"] > cfg["timelimit"] + 1.0
        out.append(
            "Max wall over all gassign runs: {mw:.1f}s (TL={tl}s){flag}.".format(
                mw=t["max_wall"], tl=cfg["timelimit"],
                flag=" -- OVER TL, timeout risk!" if over else ""))

    # production data availability
    n_prod = sum(1 for r in records if r.get("prod_obj") is not None)
    if n_prod == 0:
        out.append(
            "Production hybrid json (notes/perbay-e0-all40.json) had NO usable "
            "records for these instances (E0 may still be running) -- all prod_obj "
            "shown as '--' and verdicts are 'lose' by default.")
    elif n_prod < n:
        out.append(
            "Production data present for {p}/{n} instance(s); the rest show prod "
            "'--' (E0 still generating?).".format(p=n_prod, n=n))

    # competitor context
    if t.get("sum_gassign_obj") is not None and t.get("sum_competitor_obj"):
        out.append(
            "Context: &Sigma; gassign (feasible w/ competitor data) = {go:,.0f} vs "
            "competitor &Sigma; = {co:,.0f}.".format(
                go=t.get("sum_gassign_obj_with_comp", 0.0),
                co=t["sum_competitor_obj"]))
    return out


# --- totals -------------------------------------------------------------------
def compute_totals(records, instances_spec, timelimit):
    n_feasible = 0
    n_win = 0
    n_lose = 0
    n_infeasible = 0
    max_wall = 0.0
    sum_gassign_both = 0.0   # gassign obj over instances feasible in BOTH
    sum_prod_both = 0.0      # prod obj over the SAME set
    sum_comp = 0.0
    sum_gassign_with_comp = 0.0
    for r in records:
        if r.get("wall") is not None:
            max_wall = max(max_wall, r["wall"])
        if r.get("feasible"):
            n_feasible += 1
        else:
            n_infeasible += 1
        v = r.get("verdict")
        if v == "gassign_win":
            n_win += 1
        elif v == "lose":
            n_lose += 1
        # comparable set: feasible gassign AND a production bar exists
        if r.get("feasible") and r.get("gassign_obj") is not None \
                and r.get("prod_obj") is not None:
            sum_gassign_both += r["gassign_obj"]
            sum_prod_both += r["prod_obj"]
        if r.get("competitor_obj") is not None:
            sum_comp += r["competitor_obj"]
            if r.get("feasible") and r.get("gassign_obj") is not None:
                sum_gassign_with_comp += r["gassign_obj"]

    n = len(records)
    total_delta = (sum_gassign_both - sum_prod_both) if sum_prod_both else None
    return {
        "instances_spec": instances_spec,
        "timelimit": timelimit,
        "n_instances": n,
        "n_feasible": n_feasible,
        "n_infeasible": n_infeasible,
        "n_win": n_win,
        "n_lose": n_lose,
        "max_wall": (max_wall if records else None),
        "sum_gassign_obj": (sum_gassign_both if sum_prod_both else None),
        "sum_prod_obj": (sum_prod_both if sum_prod_both else None),
        "total_delta": total_delta,
        "sum_competitor_obj": (sum_comp if sum_comp else None),
        "sum_gassign_obj_with_comp": (sum_gassign_with_comp
                                      if sum_gassign_with_comp else None),
    }


